const UNKNOWN_ADVANCE = 0.8;

/** The width of `text` in em, each character followed by its letter-spacing. */
export function textWidthEm(text: string, letterSpacingEm: number): number {
  return [...text].reduce((sum, ch) => sum + (INTER_900_ADVANCE[ch] ?? UNKNOWN_ADVANCE) + letterSpacingEm, 0);
}
